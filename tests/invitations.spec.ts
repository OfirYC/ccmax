import { test, expect } from './fixtures';
import en from '../src/locales/en.json' with { type: 'json' };
import vi from '../src/locales/vi.json' with { type: 'json' };
import hi from '../src/locales/hi.json' with { type: 'json' };

const headers = { 'x-ccmax-request': '1' }, password = 'invitation-browser-password';

test('agents create different priced links and invitees register themselves into the right team', async ({ page, browser }) => {
  await page.addInitScript(() => localStorage.setItem('ccmax.locale', 'zh-CN'));
  expect((await page.request.post('/api/auth/login', { headers, data: { email: 'owner@example.com', password: 'e2e-owner-password' } })).ok()).toBe(true);
  const parentResponse = await page.request.post('/api/team', { headers, data: { name: '邀请人', email: 'invite-parent@example.com', password, rates: { gatelink: 0.4, ai008: 0.4, minicc: 0.4 } } });
  expect(parentResponse.ok()).toBe(true);
  const parent = (await parentResponse.json()).user;
  await page.request.post('/api/auth/login', { headers, data: { email: parent.email, password } });
  await page.goto('/team');
  const section = page.locator('.team-invitations');
  async function create(name: string, ai008: string, maxUses: string) {
    await section.getByRole('button', { name: '创建邀请链接' }).click();
    const dialog = page.getByRole('dialog', { name: '创建邀请链接' });
    await dialog.getByLabel('链接名称').fill(name);
    await dialog.getByLabel('Gatelink 结算折扣', { exact: true }).fill('0.2');
    await dialog.getByLabel('AI008 结算折扣', { exact: true }).fill(ai008);
    await dialog.getByLabel('Mini CC Gateway 结算折扣', { exact: true }).fill('0');
    await dialog.getByLabel('注册人数上限').fill(maxUses);
    await dialog.getByRole('button', { name: '生成邀请链接' }).click();
    await expect(dialog).toHaveCount(0);
    const row = section.getByRole('row').filter({ hasText: name });
    const input = row.getByRole('textbox');
    await expect(input).toHaveValue(/\/invite\/[A-Za-z0-9_-]{43}$/);
    return { row, url: await input.inputValue() };
  }
  const standard = await create('标准客户邀请', '0.1234', '1'), partner = await create('合作客户邀请', '0.05', '');
  await expect(standard.row).toContainText('× 0.1234');
  await expect(partner.row).toContainText('× 0.0500');
  expect(await section.locator('.table-scroll').evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true);
  await page.context().grantPermissions(['clipboard-read', 'clipboard-write']);
  await standard.row.getByRole('button', { name: '复制链接' }).click();
  expect(await page.evaluate(() => navigator.clipboard.readText())).toBe(standard.url);
  await standard.row.getByRole('button', { name: '复制推广文案' }).click();
  const promotion = await page.evaluate(() => navigator.clipboard.readText());
  expect(promotion).toContain(standard.url);
  expect(promotion).toContain('近 7 天、近 30 天已核实应收');
  expect(promotion).toContain('实际收入取决于有效用量和约定报价');
  await page.screenshot({ path: 'test-results/invitations-team-desktop.png', fullPage: true });
  const recipientContext = await browser.newContext();
  try {
    await recipientContext.addInitScript(() => localStorage.setItem('ccmax.locale', 'zh-CN'));
    const recipient = await recipientContext.newPage();
    await recipient.goto(standard.url);
    await expect(recipient.locator('h1')).toContainText('让闲置 Max 额度，');
    await expect(recipient.getByTestId('unit-earnings')).toHaveText('$0.2000');
    await expect(recipient.getByText('用于登录 CCMAX，可与 Claude 账号邮箱不同。', { exact: true })).toBeVisible();
    await expect(recipient.getByText('至少 12 位，请设置独立的 CCMAX 登录密码。', { exact: true })).toBeVisible();
    await recipient.screenshot({ path: 'test-results/invitation-register-desktop.png', fullPage: true });
    await recipient.getByText('查看我的结算报价', { exact: true }).click();
    await expect(recipient.locator('.invite-card')).toContainText('邀请人 邀请你加入直属团队。');
    await expect(recipient.locator('.invite-prices')).toContainText('× 0.1234');
    await expect(recipient.locator('.invite-prices')).toContainText('× 0.0000');
    await expect(recipient.locator('.invite-card')).not.toContainText('标准客户邀请');
    await recipient.getByText('用已有账单核算收入', { exact: true }).click();
    await expect(recipient.getByLabel('近 7 天实际账单（USD）')).toHaveValue('');
    await expect(recipient.getByTestId('weekly-earnings')).toHaveText('—');
    await recipient.getByLabel('近 7 天实际账单（USD）').fill('100');
    await expect(recipient.getByTestId('weekly-earnings')).toHaveText('$20.00');
    await expect(recipient.getByTestId('monthly-earnings')).toHaveText('—');
    await recipient.getByLabel('用于核算的结算报价').selectOption('minicc');
    await expect(recipient.getByTestId('weekly-earnings')).toHaveText('$0.00');
    await recipient.setViewportSize({ width: 390, height: 844 });
    expect(await recipient.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    expect(await recipient.locator('#signup').evaluate(el => Boolean(el.compareDocumentPosition(document.querySelector('.invite-guide')!) & Node.DOCUMENT_POSITION_FOLLOWING))).toBe(true);
    await recipient.getByRole('link', { name: '立即注册，添加账号', exact: true }).click();
    await expect(recipient.getByLabel('你的称呼', { exact: true })).toBeInViewport();
    await recipient.screenshot({ path: 'test-results/invitation-register-mobile.png', fullPage: true });
    await recipient.getByLabel('你的称呼', { exact: true }).fill('受邀用户');
    await recipient.getByLabel('登录邮箱', { exact: true }).fill('invite-new@example.com');
    await recipient.locator('input[name="password"]').fill(password);
    await recipient.getByLabel('确认密码', { exact: true }).fill('a-different-password');
    await recipient.getByRole('button', { name: '立即注册，添加账号' }).click();
    await expect(recipient.getByRole('alert')).toHaveText('两次输入的密码不一致');
    await recipient.getByLabel('确认密码', { exact: true }).fill(password);
    await recipient.getByRole('button', { name: '立即注册，添加账号' }).click();
    await expect(recipient.locator('h1')).toHaveText('账号已创建');
    await recipient.getByRole('link', { name: '登录并添加第一个账号', exact: true }).click();
    await recipient.getByLabel('登录邮箱', { exact: true }).fill('invite-new@example.com');
    await recipient.locator('input[name="password"]').fill(password);
    await recipient.getByRole('button', { name: '进入工作空间' }).click();
    await expect(recipient).toHaveURL(/\/accounts\?create=1$/);
    await expect(recipient.getByRole('dialog', { name: '多平台分别授权' })).toBeVisible();
    await recipient.getByRole('button', { name: '关闭弹窗', exact: true }).click();
    const self = await (await recipient.request.get('/api/auth/me')).json();
    expect(self.user.parent_id).toBe(parent.id);
    const connections = await (await recipient.request.get('/api/connections')).json();
    expect(connections.connections.find((c: any) => c.provider === 'ai008').settlement_rate).toBe('0.1234');
    expect(connections.connections.find((c: any) => c.provider === 'minicc').settlement_rate).toBe('0.0000');
    await recipient.goto(partner.url);
    await expect(recipient.locator('.invite-card')).toContainText('你当前已登录。请先退出账号，再使用邀请链接注册新成员。');
    await expect(recipient.getByRole('button', { name: '立即注册，添加账号' })).toHaveCount(0);
    await page.reload();
    await expect(section.getByRole('row').filter({ hasText: '标准客户邀请' })).toContainText('名额已满');
    const member = page.locator('.team-members-panel').getByRole('row').filter({ hasText: 'invite-new@example.com' });
    await expect(member).toContainText('× 0.1234');
    await section.getByRole('row').filter({ hasText: '合作客户邀请' }).getByRole('button', { name: '停用链接' }).click();
    await page.getByRole('dialog', { name: '停用邀请链接' }).getByRole('button', { name: '确认停用' }).click();
    await expect(section.getByRole('row').filter({ hasText: '合作客户邀请' })).toContainText('已停用');
    await recipient.request.post('/api/auth/logout', { headers, data: {} });
    await recipient.goto(partner.url);
    await expect(recipient.getByRole('alert')).toHaveText('邀请链接无效、已到期、已停用或名额已用完');
    await expect(recipient.locator('form')).toHaveCount(0);
    await expect(member).toContainText('× 0.1234');
  } finally { await recipientContext.close(); }
});

test('invitation registration supports all languages and retains form input when switching', async ({ page, request }) => {
  await request.post('/api/auth/login', { headers, data: { email: 'owner@example.com', password: 'e2e-owner-password' } });
  const response = await request.post('/api/team/invitations', { headers, data: { name: 'Language campaign', rates: { ai008: 0.12 }, expiresInDays: null } });
  expect(response.ok()).toBe(true);
  await page.goto((await response.json()).invitation.url);
  await expect(page.locator('h1')).toContainText(en['让闲置 Max 额度，']);
  await page.locator('input[name="name"]').fill('Keep my input');
  for (const [locale, catalog] of [['en', en], ['vi', vi], ['hi', hi]] as const) {
    await page.locator('.language-switcher select').selectOption(locale);
    await expect(page.locator('h1')).toContainText(catalog['让闲置 Max 额度，']);
    await expect(page.locator('input[name="name"]')).toHaveValue('Keep my input');
    await expect(page.locator('.invite-card')).not.toContainText('Gatelink');
    await expect(page.locator('.invite-card')).not.toContainText('Mini CC');
    expect((await page.locator('.invite-card').innerText()).replaceAll('平台管理员', '')).not.toMatch(/[\u3400-\u9fff]/u);
    await page.setViewportSize({ width: 390, height: 844 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  }
});
